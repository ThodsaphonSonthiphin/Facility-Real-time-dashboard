test('Admin password visibility, failed login and session restoration @smoke', async ({ page }) => {
  await page.goto('/login/admin');
  await page.getByLabel('ชื่อผู้ใช้').fill(admin.username);
  const password = page.getByLabel('รหัสผ่าน', { exact: true });
  await password.fill(randomUUID());
  await expect(password).toHaveAttribute('type', 'password');
  await page.getByRole('button', { name: 'แสดง', exact: true }).click();
  await expect(password).toHaveAttribute('type', 'text');
  await page.getByRole('button', { name: 'เข้าสู่ระบบ' }).click();
  await expect(page.getByRole('alert')).toBeVisible();
  await password.fill(admin.password);
  await page.getByRole('button', { name: 'เข้าสู่ระบบ' }).click();
  await expect(page).toHaveURL(/\/dashboard$/);
  await page.reload();
  await expect(page.getByRole('heading', { name: 'สถานะจุดทำความสะอาด' })).toBeVisible();
});

test('Building create, duplicate refusal, edit, typed confirmation, deactivate and reactivate', async ({ page }) => {
  const code = `T${randomUUID().replaceAll('-', '').slice(0, 10).toUpperCase()}`;
  const name = `อาคารทดสอบ UI ${code}`;
  await loginAsAdmin(page);
  await page.getByRole('navigation', { name: 'เมนูแอดมิน' }).getByRole('link', { name: 'ตึก', exact: true }).click();
  await page.getByRole('button', { name: 'เพิ่มตึก', exact: true }).click();
  let drawer = page.getByRole('dialog');
  await drawer.getByRole('button', { name: 'บันทึก', exact: true }).click();
  await expect(drawer.getByRole('alert')).toBeVisible();
  await drawer.getByLabel('รหัสตึก').fill(code);
  await drawer.getByLabel('ชื่อตึก').fill(name);
  await drawer.getByRole('button', { name: 'บันทึก', exact: true }).click();
  await expect(drawer).toBeHidden();
  await page.reload();
  const row = page.getByRole('row').filter({ has: page.getByRole('rowheader', { name: code, exact: true }) });
  await expect(row).toContainText(name);
  await page.getByRole('button', { name: 'เพิ่มตึก', exact: true }).click();
  drawer = page.getByRole('dialog');
  await drawer.getByLabel('รหัสตึก').fill(code);
  await drawer.getByLabel('ชื่อตึก').fill('อาคารซ้ำทดสอบ');
  await drawer.getByRole('button', { name: 'บันทึก', exact: true }).click();
  await expect(drawer.getByRole('alert')).toBeVisible();
  await expect(drawer.getByLabel('ชื่อตึก')).toHaveValue('อาคารซ้ำทดสอบ');
  await drawer.getByRole('button', { name: 'ยกเลิก' }).click();
  await row.getByRole('button', { name: `แก้ไข ตึก ${code}` }).click();
  await drawer.getByLabel('ชื่อตึก').fill(`${name} แก้ไข`);
  await drawer.getByRole('button', { name: 'บันทึก', exact: true }).click();
  await expect(row).toContainText(`${name} แก้ไข`);
  await row.getByRole('button', { name: `แก้ไข ตึก ${code}` }).click();
  await drawer.getByRole('button', { name: 'ปิดใช้งานตึกนี้' }).click();
  const confirmation = page.getByRole('alertdialog');
  await expect(confirmation.getByRole('button', { name: 'ปิดใช้งานตึก', exact: true })).toBeDisabled();
  await confirmation.getByLabel('รหัสยืนยัน').fill('WRONG');
  await expect(confirmation.getByRole('button', { name: 'ปิดใช้งานตึก', exact: true })).toBeDisabled();
  await page.keyboard.press('Escape');
  await expect(confirmation).toBeHidden();
  await expect(drawer).toBeVisible();
  await drawer.getByRole('button', { name: 'ปิดใช้งานตึกนี้' }).click();
  await confirmation.getByLabel('รหัสยืนยัน').fill(code);
  await confirmation.getByRole('button', { name: 'ปิดใช้งานตึก', exact: true }).click();
  await expect(row).toContainText('ปิดใช้งาน');
  await row.getByRole('button', { name: `แก้ไข ตึก ${code}` }).click();
  await drawer.getByRole('button', { name: 'เปิดใช้งานตึกนี้' }).click();
  await expect(row).not.toContainText('ปิดใช้งาน');
});

test('Admin account create, edit, search, inactive filter and reactivation', async ({ page }) => {
  const username = `e2e-${randomUUID()}`;
  const name = `แอดมินทดสอบ UI ${username.slice(-8)}`;
  await loginAsAdmin(page);
  await page.getByRole('navigation', { name: 'เมนูแอดมิน' }).getByRole('link', { name: 'บัญชีผู้ใช้' }).click();
  await page.getByRole('button', { name: 'สร้างบัญชี' }).click();
  const drawer = page.getByRole('dialog');
  await drawer.getByText('แอดมิน', { exact: true }).click();
  await expect(drawer.getByRole('radio', { name: 'แอดมิน', exact: true })).toBeChecked();
  await drawer.getByLabel('ชื่อที่แสดง').fill(name);
  await drawer.getByLabel('ชื่อผู้ใช้', { exact: true }).fill(username);
  await drawer.getByLabel('รหัสผ่านชั่วคราว', { exact: true }).fill(randomUUID());
  await drawer.getByRole('button', { name: 'สร้างบัญชี', exact: true }).click();
  await expect(drawer.getByRole('status')).toContainText(`สร้างบัญชี ${name} แล้ว`);
  await expect(drawer.getByLabel('รหัสผ่านชั่วคราว', { exact: true })).toBeEmpty();
  await drawer.getByRole('button', { name: 'ยกเลิก' }).click();
  await page.getByRole('tab', { name: /^แอดมิน/ }).click();
  await page.getByLabel('ค้นหา', { exact: true }).fill(username);
  const row = page.getByRole('row').filter({ hasText: username });
  await expect(row).toContainText(name);
  await row.getByRole('button', { name: `แก้ไข ${name}` }).click();
  await drawer.getByLabel('ชื่อที่แสดง').fill(`${name} แก้ไข`);
  await drawer.getByRole('button', { name: 'บันทึก', exact: true }).click();
  await expect(drawer).toBeHidden();
  await expect(row).toContainText(`${name} แก้ไข`);
  await row.getByRole('button', { name: `ปิดใช้งาน ${name} แก้ไข` }).click();
  await page.getByRole('alertdialog').getByRole('button', { name: 'ยกเลิก' }).click();
  await expect(row).toContainText('ใช้งานอยู่');
  await row.getByRole('button', { name: `ปิดใช้งาน ${name} แก้ไข` }).click();
  await page.getByRole('alertdialog').getByRole('button', { name: 'ปิดใช้งานบัญชี', exact: true }).click();
  await page.getByLabel('สถานะบัญชี').selectOption('inactive');
  await expect(row).toContainText('ปิดใช้งาน');
  await row.getByRole('button', { name: `เปิดใช้งาน ${name} แก้ไข` }).click();
  await expect(row).toHaveCount(0);
  await page.getByLabel('สถานะบัญชี').selectOption('active');
  await expect(row).toContainText('ใช้งานอยู่');
  await page.getByLabel('ค้นหา', { exact: true }).fill(`missing-${randomUUID()}`);
  await expect(page.getByText('ไม่พบบัญชีที่ตรงกับที่ค้นหา')).toBeVisible();
});

